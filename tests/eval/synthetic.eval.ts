import { describe, expect, it } from 'vitest';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { EXERCISES } from '@/features/exercises/library';
import { MovementEngine } from '@/features/movement-analysis/engine';
import { evaluateFrame } from '@/features/movement-analysis/quality';
import { SIMULATED_PROVIDER_INFO, SYNTHETIC_FRAME, buildSyntheticPose, generateFrames, seededRandom, type RepScript } from '@/features/pose-estimation/synthetic';
import { median, standardDeviation } from '@/features/movement-analysis/filters';
import type { ExerciseDefinition } from '@/types/exercise';

/**
 * Quantitative evaluation harness. Everything here runs on SYNTHETIC skeletons
 * with exactly known ground truth, so it measures the analysis software
 * (geometry, filtering, segmentation, quality gating), not the accuracy of the
 * pose model on real people. Results are written to docs/EVALUATION.md.
 * Run: npm run evaluate
 */

const lines: string[] = [];
const out = (s = '') => lines.push(s);
const r1 = (v: number) => Math.round(v * 10) / 10;

function scriptFor(def: ExerciseDefinition, rand: () => number, n: number, opts: { belowThreshold?: boolean } = {}): RepScript[] {
  const { neutral } = def.demo;
  const span = def.demo.peak - neutral;
  return Array.from({ length: n }, () => ({
    peak: opts.belowThreshold ? neutral + (def.segmentation.countMin - neutral) * (0.45 + rand() * 0.4) : neutral + span * (0.8 + rand() * 0.25),
    restMs: 700 + rand() * 1500,
    outboundMs: 700 + rand() * 2500,
    holdMs: rand() < 0.5 ? 0 : 500 + rand() * 3000,
    returnMs: 800 + rand() * 2500,
  }));
}

function run(def: ExerciseDefinition, frames: ReturnType<typeof generateFrames>) {
  const engine = new MovementEngine({ def, side: 'right', target: def.demoPrescription.target, sessionStart: 0 });
  frames.forEach((f) => engine.process(f));
  engine.tick((frames[frames.length - 1]?.timestamp ?? 0) + 5000);
  return engine;
}

describe('PocketRehab evaluation (synthetic ground truth)', () => {
  it('measures angle error, rep counting and robustness, and writes docs/EVALUATION.md', () => {
    out('# PocketRehab evaluation results');
    out();
    out(`Generated by \`npm run evaluate\` on ${new Date().toISOString().slice(0, 10)}. Every number below was produced by running the code in \`tests/eval/synthetic.eval.ts\`.`);
    out();
    out('> **What this is and is not.** These tests use synthetic skeletons whose true joint angles are known exactly. They measure the analysis software (angle geometry, smoothing, repetition segmentation and quality gating). They do **not** measure how accurately the MediaPipe model locates joints on real people, and they are **not** clinical validation. No patients or clinicians were involved.');
    out();

    // 1. Angle error vs ground truth at several landmark noise levels.
    out('## 1. Joint-angle error against known ground truth');
    out();
    out('Each value is the per-frame error between the measured angle and the exact angle used to build the skeleton (1,000 random poses per cell, 1280×720 frame). Noise is Gaussian-like pixel jitter added independently to every landmark.');
    out();
    out('| Exercise | Noise 0 px | Noise 2 px | Noise 5 px | Noise 10 px |');
    out('|---|---|---|---|---|');
    const rand = seededRandom(20261017);
    for (const def of Object.values(EXERCISES)) {
      const cells: string[] = [];
      for (const noise of [0, 2, 5, 10]) {
        const errs: number[] = [];
        for (let i = 0; i < 1000; i++) {
          const truth = def.demo.neutral + (def.demo.peak - def.demo.neutral) * rand();
          const lms = buildSyntheticPose(def, 'right', truth, { noisePx: noise, random: rand });
          const s = evaluateFrame({ timestamp: i, landmarks: lms, imageWidth: SYNTHETIC_FRAME.width, imageHeight: SYNTHETIC_FRAME.height, provider: SIMULATED_PROVIDER_INFO, status: 'ok' }, def, 'right');
          if (s.value !== null) errs.push(Math.abs(s.value - truth));
        }
        const mae = errs.reduce((a, b) => a + b, 0) / errs.length;
        const sorted = [...errs].sort((a, b) => a - b);
        const p95 = sorted[Math.floor(sorted.length * 0.95)] ?? 0;
        cells.push(`MAE ${r1(mae)}° · p95 ${r1(p95)}°`);
        if (noise === 0) expect(mae).toBeLessThan(0.01);
      }
      out(`| ${def.name} | ${cells.join(' | ')} |`);
    }
    out();
    out('With no noise the geometry is exact (error < 0.01°). Error grows with landmark jitter; real pose-model jitter on real footage has not been measured against a reference, so these numbers bound only the software, not the camera system.');
    out();

    // 2. Repetition counting.
    out('## 2. Repetition counting');
    out();
    out('20 simulated sessions per exercise, 8 repetitions each, with random peak heights (all above the counting threshold), random speeds (0.7–2.5 s out, 0.8–2.5 s back), random holds (0–3.5 s), 2 px landmark noise, 30 fps.');
    out();
    out('| Exercise | True reps | Counted | Missed | Extra (false) | Peak error (median) |');
    out('|---|---|---|---|---|---|');
    let totalTrue = 0;
    let totalCounted = 0;
    let totalExtra = 0;
    for (const def of Object.values(EXERCISES)) {
      let trueN = 0;
      let counted = 0;
      let missed = 0;
      let extra = 0;
      const peakErr: number[] = [];
      for (let k = 0; k < 20; k++) {
        const rr = seededRandom(1000 + k);
        const script = scriptFor(def, rr, 8);
        const engine = run(def, generateFrames(def, 'right', def.demo.neutral, script, { noisePx: 2, random: rr }));
        trueN += script.length;
        counted += engine.reps.length;
        missed += Math.max(0, script.length - engine.reps.length);
        extra += Math.max(0, engine.reps.length - script.length);
        engine.reps.forEach((rep, i) => {
          const truth = script[i]?.peak;
          if (truth !== undefined) peakErr.push(Math.abs(rep.peakValue - truth));
        });
      }
      totalTrue += trueN;
      totalCounted += counted;
      totalExtra += extra;
      out(`| ${def.name} | ${trueN} | ${counted} | ${missed} | ${extra} | ${r1(median(peakErr) ?? 0)}° |`);
    }
    out();
    out(`Overall: ${totalCounted} of ${totalTrue} scripted repetitions counted (${r1((totalCounted / totalTrue) * 100)}%), ${totalExtra} extra.`);
    out();

    // 3. Movements that should NOT count.
    out('## 3. Movements that must not be counted');
    out();
    out('| Scenario | Movements | Counted (should be 0) | Recorded as not counted |');
    out('|---|---|---|---|');
    {
      let n = 0;
      let counted = 0;
      let incomplete = 0;
      for (const def of Object.values(EXERCISES)) {
        for (let k = 0; k < 10; k++) {
          const rr = seededRandom(5000 + k);
          const script = scriptFor(def, rr, 5, { belowThreshold: true });
          const engine = run(def, generateFrames(def, 'right', def.demo.neutral, script, { noisePx: 2, random: rr }));
          n += script.length;
          counted += engine.reps.length;
          incomplete += engine.incompleteAttempts.length;
        }
      }
      out(`| Partial movements that never reach the counting threshold (all exercises) | ${n} | ${counted} | ${incomplete} |`);
      expect(counted).toBe(0);
    }
    {
      const def = EXERCISES['shoulder-abduction'];
      let spikes = 0;
      let counted = 0;
      for (let k = 0; k < 20; k++) {
        const frames = generateFrames(def, 'right', def.demo.neutral, [{ peak: def.demo.neutral, restMs: 6000, outboundMs: 10, holdMs: 0, returnMs: 10 }], {
          noisePx: 2,
          random: seededRandom(7000 + k),
          offsetAt: (t) => (Math.floor(t / 33) % 37 === 5 ? 75 : 0),
        });
        spikes += frames.filter((_, i) => i % 37 === 5).length;
        counted += run(def, frames).reps.length;
      }
      out(`| Single-frame tracking glitches of +75° at rest (arm raise) | ${spikes} | ${counted} | — |`);
      expect(counted).toBe(0);
    }
    {
      const def = EXERCISES['shoulder-abduction'];
      let windows = 0;
      let counted = 0;
      for (let k = 0; k < 20; k++) {
        const rr = seededRandom(8000 + k);
        const frames: ReturnType<typeof generateFrames> = [];
        let t = 1000;
        for (let i = 0; i < 300; i++, t += 33.3) {
          const v = 25 + (rr() - 0.5) * 10;
          frames.push({ timestamp: t, landmarks: buildSyntheticPose(def, 'right', v, { noisePx: 3, random: rr }), imageWidth: 1280, imageHeight: 720, provider: SIMULATED_PROVIDER_INFO, status: 'ok' });
        }
        windows++;
        counted += run(def, frames).reps.length;
      }
      out(`| 10 s of jitter around the start position (±5°, 3 px noise) | ${windows} sessions | ${counted} | — |`);
      expect(counted).toBe(0);
    }
    out();

    // 4. Robustness: occlusion and dropouts.
    out('## 4. Occlusion, dropped frames and camera interruptions');
    out();
    out('Arm raise, 8 repetitions per session, 10 sessions per row.');
    out();
    out('| Condition | Reps counted / true | Reps marked reliable | Reps excluded as uncertain | Sessions usable for trends |');
    out('|---|---|---|---|---|');
    const def = EXERCISES['shoulder-abduction'];
    const conditions: Array<{ label: string; opts: (rr: () => number) => Parameters<typeof generateFrames>[4] }> = [
      { label: 'Clean (2 px noise)', opts: (rr) => ({ noisePx: 2, random: rr }) },
      { label: 'Elbow partly hidden (visibility 0.5) all session', opts: (rr) => ({ noisePx: 2, random: rr, visibility: { 14: 0.5 } }) },
      { label: 'Elbow hidden (visibility 0.1) 30% of the time', opts: (rr) => ({ noisePx: 2, random: rr, visibilityAt: (t) => (Math.floor(t / 1000) % 10 < 3 ? { 14: 0.1 } : undefined) }) },
      { label: '5% of frames with no person detected', opts: (rr) => ({ noisePx: 2, random: rr, dropFrame: () => rr() < 0.05 }) },
      { label: '20% of frames with no person detected', opts: (rr) => ({ noisePx: 2, random: rr, dropFrame: () => rr() < 0.2 }) },
      { label: '1-second camera freeze once per session', opts: (rr) => ({ noisePx: 2, random: rr, dropFrame: (t) => t > 9000 && t < 10000 }) },
      { label: 'Body turned side-on, so the view check fails', opts: (rr) => ({ noisePx: 2, random: rr }) },
    ];
    for (const c of conditions) {
      let trueN = 0;
      let counted = 0;
      let reliable = 0;
      let uncertain = 0;
      let usable = 0;
      for (let k = 0; k < 10; k++) {
        const rr = seededRandom(9000 + k);
        const script = scriptFor(def, rr, 8);
        let frames = generateFrames(def, 'right', def.demo.neutral, script, c.opts(rr));
        if (c.label.startsWith('Body turned')) {
          // Re-use the side-view (knee) skeleton's shoulders/hips so the view check sees a side-on body.
          frames = frames.map((f) => {
            if (!f.landmarks) return f;
            const side = buildSyntheticPose(EXERCISES['knee-extension'], 'right', 100);
            const lms = f.landmarks.map((l, i) => (i === 11 || i === 23 ? (side[i] ?? l) : l));
            return { ...f, landmarks: lms };
          });
        }
        const engine = run(def, frames);
        trueN += script.length;
        counted += engine.reps.length;
        reliable += engine.reps.filter((r) => r.validity === 'reliable').length;
        uncertain += engine.reps.filter((r) => r.validity === 'uncertain').length;
        if (engine.fingerprint().valid) usable++;
      }
      out(`| ${c.label} | ${counted} / ${trueN} | ${reliable} | ${uncertain} | ${usable} / 10 |`);
    }
    out();
    out('Missing or hidden landmarks abort the affected repetition instead of guessing it; partial visibility keeps counting but excludes the measurements. A mismatched camera view marks frames uncertain, so those repetitions are excluded from measurements.');
    out();

    // 5. Software repeatability.
    out('## 5. Repeatability under simulated noise');
    out();
    out('The same scripted movement (8 repetitions peaking at exactly 90°) was "recorded" 30 times with different random 3 px landmark noise. This is the variation the software alone adds; real camera sessions vary much more (placement, distance, clothing, lighting, the person).');
    out();
    const peaks: number[] = [];
    for (let k = 0; k < 30; k++) {
      const rr = seededRandom(11000 + k);
      const script: RepScript[] = Array.from({ length: 8 }, () => ({ peak: 90, restMs: 900, outboundMs: 1400, holdMs: 400, returnMs: 1500 }));
      const fp = run(def, generateFrames(def, 'right', 15, script, { noisePx: 3, random: rr })).fingerprint();
      if (fp.peakMedian !== null) peaks.push(fp.peakMedian);
    }
    const sd = standardDeviation(peaks) ?? 0;
    out(`Session median peak: mean ${r1(peaks.reduce((a, b) => a + b, 0) / peaks.length)}°, standard deviation ${r1(sd)}°, range ${r1(Math.min(...peaks))}–${r1(Math.max(...peaks))}° (n = ${peaks.length}).`);
    out();
    out('Because real-camera repeatability has not been measured, PocketRehab does not set a minimal detectable change (`MEASUREMENT_ERROR_MODEL = null`) and never calls a change "improvement".');
    out();

    // 6. Real footage run, when available.
    out('## 6. Real footage (MediaPipe on a real person)');
    out();
    const real = 'docs/evaluation/real-video-run.json';
    if (existsSync(real)) {
      const j = JSON.parse(readFileSync(real, 'utf8')) as Record<string, string>;
      out(`Recorded by \`tests/e2e/real-person.spec.ts\` on ${String(j.ranAt).slice(0, 10)}: the browser's fake camera played *${j.clip}* while the real MediaPipe Pose Landmarker ran in the page.`);
      out();
      const num = (text: string | undefined, re: RegExp) => re.exec(text ?? '')?.slice(1).join(' of ') ?? 'not recorded';
      out(`| Measure | Result |`);
      out(`|---|---|`);
      out(`| Person detected and "facing the camera" check passed | yes (the test waits for both) |`);
      out(`| Frames with reliable tracking during the session | ${num(j.reliableText, /(\d+)%/)}% |`);
      out(`| Repetitions counted (arm raise definition, 25 s of jumping jacks and burpees) | ${num(j.repsText, /counted\s*(\d+)/)} |`);
      out(`| Movements seen but not counted (too fast, too small or tracking lost) | ${num(j.notCountedText, /(\d+)\s*$/)} |`);
      out(`| Live arm-angle readout at the end of the run | ${num(j.angleText, /(\d+)°/)}° |`);
      out(`| Processing rate in headless Chromium (software graphics, no GPU) | ${num(j.fpsText, /(\d+) frames/)} frames/s |`);
      out(`| Page errors | ${Array.isArray(j.pageErrors) && j.pageErrors.length ? j.pageErrors.length : 0} |`);
      out();
      out('The headless test browser has no hardware GPU, so its frame rate is far below a normal browser on a laptop; the app automatically drops to a reduced rate and keeps checking quality. Frame rate on real laptops was not measured in this build.');
      out();
      out('The clip shows fast jumping jacks and burpees, not a rehab exercise, so this run checks detection, the setup checks and the quality states on real footage. It is one clip of one person and is not an accuracy measurement.');
    } else {
      out('Not run on this machine (the test clip is downloaded by `sh scripts/fetch-test-video.sh`).');
    }
    out();

    out('## 7. Not yet evaluated');
    out();
    out('- Joint-angle accuracy of the camera system against a goniometer or motion-capture reference.');
    out('- Performance across camera angles, distances, lighting, clothing, body types and skin tones on real people.');
    out('- Calibration of the tracking-quality states against real measurement error.');
    out('- Repeatability across real sessions, and therefore a minimal detectable change.');
    out('- Any clinical outcome. Doing these properly needs consented participants and appropriate oversight.');
    out();

    mkdirSync('docs', { recursive: true });
    writeFileSync('docs/EVALUATION.md', lines.join('\n') + '\n');
  });
});
